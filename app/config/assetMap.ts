/**
 * Asset mapping: logical component ids → node/material names inside a specific model.
 * The app never hard-codes node names; swap models by adding another map.
 * For a third-party model, run `npm run inspect:glb -- <file>` and fill in the candidates.
 */
import type { GroupId } from '../types/configurator'

export const COMPONENT_IDS = [
  'frame_main',
  'fork',
  'wheel_front',
  'wheel_rear',
  'tire_front',
  'tire_rear',
  'crankset',
  'cassette',
  'chain',
  'derailleur_front',
  'derailleur_rear',
  'handlebar',
  'stem',
  'bar_tape',
  'saddle',
  'seatpost',
  'brake_front',
  'brake_rear',
] as const

export type ComponentId = (typeof COMPONENT_IDS)[number]

/** How a configurator group is represented in 3D for a given model. */
export type GroupVisual =
  | { kind: 'paint' }
  | {
      kind: 'component'
      /** Component slots replaced together (e.g. both wheels). Each slot is a node name in the variant file. */
      slots: ComponentId[]
      /** Variant key → component GLB containing nodes named after `slots`. */
      variants: Record<string, string>
      /** Builds the variant key from the selections when it depends on more than one group (frame@size). */
      compose?: (selections: Partial<Record<GroupId, string | null>>) => string | null
    }
  /** Shown through another group's variant (size → the frame for that size). Honest only if that variant is mounted. */
  | { kind: 'derived'; from: GroupId; note: string }
  | { kind: 'material'; target: 'barTape'; variants: Record<string, { color: string; roughness: number; metalness?: number }> }

export interface ModelAssetMap {
  id: string
  url: string
  /** Shown in the viewer so nobody mistakes the asset's origin. */
  source: { label: string; license: string; procedural: boolean }
  /** Candidate node names per component; first match wins (case-insensitive). Missing = unsupported. */
  components: Partial<Record<ComponentId, string[]>>
  /** Materials that receive frame paint / bar-tape colour. */
  materials: { paint: string[]; barTape: string[] }
  /** Groups the model can visualise. Groups not listed are reported as "not shown in 3D". */
  visuals: Partial<Record<GroupId, GroupVisual>>
  /** Which option each swappable group shows as baked into the base model file. */
  bakedVariants: Partial<Record<GroupId, string>>
  /** Why a group is not visualised (shown in the UI). */
  notes: Partial<Record<GroupId, string>>
  /** Exploded-view offsets per node (metres, parent space). Nested parts add up. */
  explode: Record<string, [number, number, number]>
}

